function fig = createThesisFigure(sizeSpec, varargin)
%CREATETHESISFIGURE Create a figure sized for thesis-ready export.

    figSizeCm = thesisFigureSize(sizeSpec);
    fig = figure( ...
        'Color', 'w', ...
        'Units', 'centimeters', ...
        'Position', [2 2 figSizeCm], ...
        'PaperUnits', 'centimeters', ...
        'PaperPosition', [0 0 figSizeCm], ...
        'PaperSize', figSizeCm, ...
        'PaperPositionMode', 'auto', ...
        'InvertHardcopy', 'off', ...
        varargin{:});
end
